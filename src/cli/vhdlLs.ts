import * as path from 'path';
import { generateVhdlLsConfig } from '../services/vhdlLsConfig/generateVhdlLsConfig';
import type { VhdlLsConfigSummary } from '../services/vhdlLsConfig/generateVhdlLsConfig';

export interface CliVhdlLsArgs {
  /** Workspace root the vhdl_ls.toml is written to (default: the current directory). */
  root: string;
  /** Print the file text instead of writing it. */
  dryRun: boolean;
  /** Replace a vhdl_ls.toml that IPCraft did not write (a backup is kept). */
  force: boolean;
}

const plural = (n: number, one: string, many: string): string => `${n} ${n === 1 ? one : many}`;

function printDetails(summary: VhdlLsConfigSummary, log: (message: string) => void): void {
  if (summary.excludedFiles > 0) {
    log(
      `Excluded ${plural(summary.excludedFiles, 'file', 'files')}; see the "# excluded:" comments.`
    );
  }
  if (summary.missingLibraries.length > 0) {
    log(`Missing libraries (proposed in the user section): ${summary.missingLibraries.join(', ')}`);
  }
  if (summary.skippedEntries > 0) {
    log(
      `Skipped ${plural(summary.skippedEntries, 'manifest entry', 'manifest entries')} that could not be resolved.`
    );
  }
  if (summary.unscannedFiles > 0) {
    log(
      `${plural(summary.unscannedFiles, 'file was', 'files were')} not scanned for duplicate units.`
    );
  }
}

/** Core logic behind `ipcraft vhdl-ls`: prints the outcome and returns the process exit code. */
export async function runCliVhdlLs(args: CliVhdlLsArgs): Promise<number> {
  const result = await generateVhdlLsConfig({
    root: path.resolve(args.root),
    force: args.force,
    dryRun: args.dryRun,
  });
  switch (result.status) {
    case 'error':
      console.error(result.message);
      return 1;
    case 'needsConfirmation':
      console.error(
        `${result.configPath} was not generated by IPCraft (or was edited). Re-run with --force to replace it; a backup is saved to .ipcraft/backup/.`
      );
      return 2;
    case 'dryRun':
      process.stdout.write(result.text);
      printDetails(result.summary, (m) => console.error(m));
      return 0;
    case 'unchanged':
      console.log(`Up to date: ${result.configPath}`);
      printDetails(result.summary, (m) => console.log(m));
      return 0;
    case 'written':
      console.log(
        `Wrote ${result.configPath}: ${plural(result.summary.libraries, 'library', 'libraries')}, ${plural(result.summary.files, 'file', 'files')}`
      );
      if (result.backupPath) {
        console.log(`Backup of the previous file: ${result.backupPath}`);
      }
      printDetails(result.summary, (m) => console.log(m));
      return 0;
  }
}
