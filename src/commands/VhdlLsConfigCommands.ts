/**
 * VS Code command that writes a root vhdl_ls.toml (issue #275). A thin adapter over
 * generateVhdlLsConfig; the CLI `ipcraft vhdl-ls` shares the same service.
 */

import * as vscode from 'vscode';
import { safeRegisterCommand } from '../utils/vscodeHelpers';
import { CONFIG_KEY_IPCRAFT } from '../utils/configKeys';
import {
  generateVhdlLsConfig,
  type VhdlLsConfigResult,
  type VhdlLsConfigSummary,
} from '../services/vhdlLsConfig/generateVhdlLsConfig';
import { resolveVendorInstalls } from '../services/vhdlLsConfig/vendorLibraries';

async function pickFolder(): Promise<vscode.WorkspaceFolder | undefined> {
  const folders = vscode.workspace.workspaceFolders;
  if (!folders || folders.length === 0) {
    void vscode.window.showErrorMessage('Open a folder to generate vhdl_ls.toml.');
    return undefined;
  }
  if (folders.length === 1) {
    return folders[0];
  }
  void vscode.window.showWarningMessage(
    'rust_hdl reads only one vhdl_ls.toml per workspace; choose the folder to write it to.'
  );
  return vscode.window.showWorkspaceFolderPick();
}

function vendorInstalls(folder: vscode.WorkspaceFolder): ReturnType<typeof resolveVendorInstalls> {
  const cfg = vscode.workspace.getConfiguration(CONFIG_KEY_IPCRAFT, folder.uri);
  return resolveVendorInstalls({
    vivadoInstallDirs: cfg.get<string[]>('vivado.installDirs', []),
    vivadoInstallDir: cfg.get<string>('vivado.installDir'),
    vivadoPinnedVersion: cfg.get<string>('vivado.pinnedVersion'),
    quartusInstallDirs: cfg.get<string[]>('quartus.installDirs', []),
    quartusInstallDir: cfg.get<string>('quartus.installDir'),
    quartusPinnedVersion: cfg.get<string>('quartus.pinnedVersion'),
  });
}

function describe(summary: VhdlLsConfigSummary): string {
  const parts = [`${summary.libraries} libraries, ${summary.files} files`];
  if (summary.excludedDuplicates > 0) {
    parts.push(`${summary.excludedDuplicates} duplicates excluded`);
  }
  if (summary.missingLibraries.length > 0) {
    parts.push(`missing libraries proposed: ${summary.missingLibraries.join(', ')}`);
  }
  return `vhdl_ls.toml: ${parts.join('; ')}.`;
}

async function report(result: VhdlLsConfigResult): Promise<void> {
  if (result.status === 'error') {
    void vscode.window.showErrorMessage(result.message);
  } else if (result.status === 'written' || result.status === 'unchanged') {
    const action = await vscode.window.showInformationMessage(describe(result.summary), 'Open');
    if (action === 'Open') {
      await vscode.window.showTextDocument(vscode.Uri.file(result.configPath));
    }
  }
}

export function registerVhdlLsConfigCommands(context: vscode.ExtensionContext): void {
  safeRegisterCommand(
    context,
    'fpga-ip-core.generateVhdlLsConfig',
    async () => {
      const folder = await pickFolder();
      if (!folder) {
        return;
      }
      const options = {
        root: folder.uri.fsPath,
        dryRun: false,
        vendorInstalls: vendorInstalls(folder),
      };
      let result = await generateVhdlLsConfig({ ...options, force: false });
      if (result.status === 'needsConfirmation') {
        const answer = await vscode.window.showWarningMessage(
          'vhdl_ls.toml was not generated by IPCraft (or was edited). Replace it? A backup is saved to .ipcraft/backup/.',
          { modal: true },
          'Replace'
        );
        if (answer !== 'Replace') {
          return;
        }
        result = await generateVhdlLsConfig({ ...options, force: true });
      }
      await report(result);
    },
    { requiresWorkspaceTrust: true }
  );
}
