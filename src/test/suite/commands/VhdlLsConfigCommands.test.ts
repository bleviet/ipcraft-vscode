import * as vscode from 'vscode';
import { registerVhdlLsConfigCommands } from '../../../commands/VhdlLsConfigCommands';
import { generateVhdlLsConfig } from '../../../services/vhdlLsConfig/generateVhdlLsConfig';

jest.mock('../../../services/vhdlLsConfig/generateVhdlLsConfig');
jest.mock('../../../utils/workspaceTrust', () => ({
  // A plain function: `resetMocks` would wipe a jest.fn implementation before each test.
  requireWorkspaceTrust: () => Promise.resolve(true),
}));

const generate = generateVhdlLsConfig as jest.Mock;
const win = vscode.window as unknown as Record<string, jest.Mock>;
const ws = vscode.workspace as unknown as { workspaceFolders: unknown };

const folder = (fsPath: string) => ({ uri: { fsPath }, name: fsPath, index: 0 });
const summary = {
  libraries: 2,
  files: 5,
  excludedDuplicates: 0,
  missingLibraries: [],
  skippedEntries: 0,
  unscannedFiles: 0,
};
const written = { status: 'written', configPath: '/ws/vhdl_ls.toml', text: '', summary };

async function runCommand(): Promise<void> {
  const context = { subscriptions: [] as unknown[] };
  registerVhdlLsConfigCommands(context as unknown as vscode.ExtensionContext);
  const registered = (vscode.commands.registerCommand as jest.Mock).mock.calls.find(
    ([id]) => id === 'fpga-ip-core.generateVhdlLsConfig'
  );
  await (registered?.[1] as () => Promise<void>)();
}

beforeEach(() => {
  win.showWorkspaceFolderPick = jest.fn();
  (vscode.workspace.getConfiguration as jest.Mock).mockReturnValue({
    get: (_key: string, fallback?: unknown) => fallback,
  });
  ws.workspaceFolders = [folder('/ws')];
});

describe('generateVhdlLsConfig command', () => {
  it('shows an error without a workspace folder', async () => {
    ws.workspaceFolders = undefined;
    await runCommand();
    expect(win.showErrorMessage).toHaveBeenCalledWith('Open a folder to generate vhdl_ls.toml.');
    expect(generate).not.toHaveBeenCalled();
  });

  it('uses the only folder without asking', async () => {
    generate.mockResolvedValue(written);
    await runCommand();
    expect(win.showWorkspaceFolderPick).not.toHaveBeenCalled();
    expect(generate).toHaveBeenCalledWith(
      expect.objectContaining({ root: '/ws', force: false, dryRun: false })
    );
  });

  it('warns and asks which folder to use when there are several', async () => {
    ws.workspaceFolders = [folder('/a'), folder('/b')];
    win.showWorkspaceFolderPick.mockResolvedValue(folder('/b'));
    generate.mockResolvedValue(written);
    await runCommand();
    expect(win.showWarningMessage).toHaveBeenCalledWith(
      'rust_hdl reads only one vhdl_ls.toml per workspace; choose the folder to write it to.'
    );
    expect(generate).toHaveBeenCalledWith(expect.objectContaining({ root: '/b' }));
  });

  it('does nothing when the folder pick is cancelled', async () => {
    ws.workspaceFolders = [folder('/a'), folder('/b')];
    win.showWorkspaceFolderPick.mockResolvedValue(undefined);
    await runCommand();
    expect(generate).not.toHaveBeenCalled();
  });

  it('reruns with force after the user confirms Replace', async () => {
    generate
      .mockResolvedValueOnce({
        status: 'needsConfirmation',
        configPath: '/ws/vhdl_ls.toml',
        ownership: 'user',
      })
      .mockResolvedValueOnce(written);
    win.showWarningMessage.mockResolvedValue('Replace');
    await runCommand();
    expect(win.showWarningMessage).toHaveBeenCalledWith(
      'vhdl_ls.toml was not generated by IPCraft (or was edited). Replace it? A backup is saved to .ipcraft/backup/.',
      { modal: true },
      'Replace'
    );
    expect(generate).toHaveBeenLastCalledWith(expect.objectContaining({ force: true }));
    expect(win.showInformationMessage).toHaveBeenCalled();
  });

  it('stops when the user cancels the confirmation', async () => {
    generate.mockResolvedValue({
      status: 'needsConfirmation',
      configPath: '/ws/vhdl_ls.toml',
      ownership: 'edited',
    });
    win.showWarningMessage.mockResolvedValue(undefined);
    await runCommand();
    expect(generate).toHaveBeenCalledTimes(1);
    expect(win.showInformationMessage).not.toHaveBeenCalled();
  });

  it('opens the file when the user picks Open', async () => {
    generate.mockResolvedValue(written);
    win.showInformationMessage.mockResolvedValue('Open');
    await runCommand();
    expect(vscode.Uri.file).toHaveBeenCalledWith('/ws/vhdl_ls.toml');
    expect(win.showTextDocument).toHaveBeenCalled();
  });

  it('shows the service error message', async () => {
    generate.mockResolvedValue({
      status: 'error',
      configPath: '/ws/vhdl_ls.toml',
      message: 'bad toml',
    });
    await runCommand();
    expect(win.showErrorMessage).toHaveBeenCalledWith('bad toml');
  });
});
