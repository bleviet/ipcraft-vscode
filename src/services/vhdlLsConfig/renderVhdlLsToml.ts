/**
 * Renders the vhdl_ls.toml text: header with the generated-section hash, the generated
 * libraries, and the user section with appended "Missing library" proposals. Pure; output is
 * always LF.
 */

import { createHash } from 'crypto';
import type { GeneratedLibrary, MissingLibrary } from './buildLibraryMap';
import type { VendorFiles } from './vendorLibraries';

export const HEADER_HASH_PREFIX = '# ipcraft-generated sha256=';
export const GENERATED_START = '# ==== IPCraft generated section ====';
export const GENERATED_END = '# ==== End of IPCraft generated section ====';
export const USER_MARKER = '# ==== User section: IPCraft only appends proposals here ====';

const HEADER_LINES = [
  '# Generated by IPCraft. Regenerate with "IPCraft: Generate vhdl_ls.toml"',
  '# or `ipcraft vhdl-ls`. Edit only the user section at the end.',
];

const THIRD_PARTY = new Set([
  'unisim',
  'unimacro',
  'xpm',
  'altera_mf',
  'altera_lnsim',
  'lpm',
  'altera',
  'osvvm',
  'vunit_lib',
  'uvvm_util',
  'uvvm_vvc_framework',
]);

/** SHA-256 of the lines between the generated start and end markers, joined with LF. */
export function hashGeneratedLines(lines: string[]): string {
  return createHash('sha256').update(lines.join('\n')).digest('hex');
}

const SHORT_ESCAPES: Record<string, string> = {
  '\b': '\\b',
  '\t': '\\t',
  '\n': '\\n',
  '\f': '\\f',
  '\r': '\\r',
  '"': '\\"',
  '\\': '\\\\',
};

/** Escapes backslash, quote and control characters the way a TOML basic string needs. */
function escapeText(value: string): string {
  return value.replace(
    /[\u0000-\u001f\u007f"\\]/g,
    (ch) => SHORT_ESCAPES[ch] ?? `\\u${ch.charCodeAt(0).toString(16).padStart(4, '0')}`
  );
}

function basicString(value: string): string {
  return `"${escapeText(value)}"`;
}

/** Comment text must stay on one line: control characters are shown escaped. */
function commentText(value: string): string {
  return value.replace(/[\u0000-\u001f\u007f]/g, (ch) => escapeText(ch));
}

function quoteKey(name: string): string {
  return /^[A-Za-z0-9_-]+$/.test(name) ? name : basicString(name);
}

function quotePath(value: string): string {
  return /['\u0000-\u001f\u007f]/.test(value) ? basicString(value) : `'${value}'`;
}

function renderLibrary(library: GeneratedLibrary): string[] {
  return [
    `libraries.${quoteKey(library.name)}.files = [`,
    ...library.files.map((f) => `  ${quotePath(f.path)},  # ${commentText(f.provenance)}`),
    ...library.excluded.map(
      (f) => `  # excluded: ${commentText(f.path)}, ${commentText(f.reason)}`
    ),
    ']',
  ];
}

/** Everything before the user section's content, ending with the user marker line. */
export function renderHead(libraries: GeneratedLibrary[]): string {
  const generated = libraries.flatMap(renderLibrary);
  return [
    ...HEADER_LINES,
    `${HEADER_HASH_PREFIX}${hashGeneratedLines(generated)}`,
    '',
    GENERATED_START,
    ...generated,
    GENERATED_END,
    '',
    USER_MARKER,
  ].join('\n');
}

function dirOfPattern(pattern: string): string {
  const slash = pattern.lastIndexOf('/');
  return slash === -1 ? './' : pattern.slice(0, slash + 1);
}

function renderProposal(
  missing: MissingLibrary,
  vendorFiles: ReadonlyMap<string, VendorFiles>
): string {
  const { name, firstUse, otherFiles, candidates } = missing;
  const key = quoteKey(name);
  const others =
    otherFiles > 0 ? ` and ${otherFiles} other file${otherFiles === 1 ? '' : 's'}` : '';
  const lines = [
    `# Missing library ${name}, used by ${commentText(firstUse.file)}:${firstUse.line}${others}.`,
  ];

  const vendor = vendorFiles.get(name);
  let files: string[];
  if (vendor) {
    files = vendor.files;
    lines.push(`# Path from ${vendor.setting} (${vendor.version}):`);
  } else if (candidates.length > 0) {
    files = candidates;
    lines.push(
      `# Packages it should provide were found in: ${commentText([...new Set(candidates.map(dirOfPattern))].join(', '))}`
    );
  } else {
    files = [`<path to ${name} sources>/*.vhd`];
  }
  if (name === 'vunit_lib') {
    lines.push(
      '# VUnit ships files for several VHDL standards; add an exclude pattern for the ones you do not use.'
    );
  }
  lines.push(`# [libraries.${key}]`, `# files = [${files.map(quotePath).join(', ')}]`);
  if (THIRD_PARTY.has(name)) {
    lines.push('# is_third_party = true');
  }
  return lines.join('\n');
}

/**
 * Appends a commented proposal per missing library that the user section does not mention.
 * Existing user text is preserved verbatim.
 */
export function appendProposals(
  userText: string,
  missing: MissingLibrary[],
  proposed: ReadonlySet<string>,
  vendorFiles: ReadonlyMap<string, VendorFiles>
): string {
  const blocks = missing
    .filter((m) => !proposed.has(m.name))
    .map((m) => renderProposal(m, vendorFiles));
  if (blocks.length === 0) {
    return userText;
  }
  let text = userText;
  if (text.trim() !== '' && !text.endsWith('\n')) {
    text += '\n';
  }
  for (const block of blocks) {
    if (text.trim() !== '' && !text.endsWith('\n\n')) {
      text += '\n';
    }
    text += `${block}\n`;
  }
  return text;
}

export function renderVhdlLsToml(libraries: GeneratedLibrary[], userText: string): string {
  return `${renderHead(libraries)}\n${userText}`;
}
